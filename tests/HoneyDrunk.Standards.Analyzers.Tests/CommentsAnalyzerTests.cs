using AwesomeAssertions;
using HoneyDrunk.Standards.Analyzers.Comments;
using Xunit;

namespace HoneyDrunk.Standards.Analyzers.Tests;

public sealed class CommentsAnalyzerTests
{
    [Theory]
    [InlineData("// var total = order.Lines.Sum(line => line.Price);")]
    [InlineData("// await repository.SaveAsync(order);")]
    [InlineData("// return Results.Ok(order);")]
    [InlineData("// throw exception;")]
    [InlineData("// break;")]
    [InlineData("// continue;")]
    public async Task CommentedOutStatement_IsReported(string comment)
    {
        var diagnostics = await RunAsync(Method(comment));

        diagnostics.Select(diagnostic => diagnostic.Id).Should().Equal("HD0110");
    }

    [Fact]
    public async Task CommentedOutBlock_IsReportedOnce()
    {
        var diagnostics = await RunAsync(Method("""
            // if (order.IsPaid)
            // {
            //     order.Ship();
            // }
            """));

        diagnostics.Select(diagnostic => diagnostic.Id).Should().Equal("HD0110");
    }

    [Theory]
    [InlineData("/* order.Cancel(); */")]
    [InlineData("/*\n * var total = order.Total;\n * return total;\n */")]
    public async Task CommentedOutCodeInBlockComment_IsReported(string comment)
    {
        var diagnostics = await RunAsync(Method(comment));

        diagnostics.Select(diagnostic => diagnostic.Id).Should().Equal("HD0110");
    }

    [Fact]
    public async Task ProseBlockComment_IsAllowed()
    {
        var diagnostics = await RunAsync(Method("/* The provider rounds half up; match it here. */"));

        diagnostics.Should().BeEmpty();
    }

    [Theory]
    [InlineData("// Retry once: the provider drops the first call after a cold start.")]
    [InlineData("// The total excludes tax; tax is added at checkout.")]
    [InlineData("// See https://learn.microsoft.com/ef/core for the mapping rules.")]
    [InlineData("// Arrange")]
    [InlineData("// See above;")]
    public async Task IntentComments_AreAllowed(string comment)
    {
        var diagnostics = await RunAsync(Method(comment));

        diagnostics.Should().BeEmpty();
    }

    [Theory]
    [InlineData("// TODO: handle refunds")]
    [InlineData("// FIXME this breaks on leap years")]
    [InlineData("/* HACK: skip validation */")]
    [InlineData("/// <summary>TODO describe this.</summary>")]
    public async Task UntrackedDeferredWork_IsReported(string comment)
    {
        var diagnostics = await RunAsync(comment + "\npublic sealed class Order { }");

        diagnostics.Select(diagnostic => diagnostic.Id).Should().Equal("HD0111");
    }

    [Theory]
    [InlineData("// TODO(#42): handle refunds")]
    [InlineData("// TODO handle refunds, see https://github.com/HoneyDrunkStudios/HoneyDrunk.Payments/issues/42")]
    [InlineData("// TODO PAY-42 handle refunds")]
    public async Task TrackedDeferredWork_IsAllowed(string comment)
    {
        var diagnostics = await RunAsync(comment + "\npublic sealed class Order { }");

        diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task ReferenceOnTheNextCommentLine_TracksTheTodo()
    {
        var diagnostics = await RunAsync(Method("""
            // TODO(data): back the accumulator with a repository for
            // durability across restarts per ADR-0018 D12.
            """));

        diagnostics.Should().BeEmpty();
    }

    [Theory]
    [InlineData("// SQLite cannot translate DateTimeOffset comparisons in LINQ;\n// store as ticks so numeric comparison works in test queries.")]
    [InlineData("// Persist the canonical envelope directly in this unit's transaction;\n// an independent writer must not commit audit ahead of the quest ledger.")]
    [InlineData("// Defer to the base which flips the disposed sentinel and clears its\n// private fields; without this CA2215 (call base.DisposeAsync) trips.")]
    public async Task ProseEndingInSemicolons_IsNotCode(string comment)
    {
        var diagnostics = await RunAsync(Method(comment));

        diagnostics.Should().BeEmpty();
    }

    [Fact]
    public async Task GeneratedCode_IsSkipped()
    {
        var diagnostics = await RunAsync("// <auto-generated/>\n" + Method("// var total = order.Total;"));

        diagnostics.Should().BeEmpty();
    }

    private static string Method(string comment) =>
        "public sealed class OrderService\n{\n    public void Ship()\n    {\n" + comment + "\n    }\n}\n";

    private static Task<IReadOnlyList<Microsoft.CodeAnalysis.Diagnostic>> RunAsync(string source) =>
        AnalyzerHarness.RunAsync(new CommentsAnalyzer(), source, withEntityFramework: false);
}
