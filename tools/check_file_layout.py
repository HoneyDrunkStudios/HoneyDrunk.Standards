#!/usr/bin/env python3
"""Check owned C# file sizes and folder layout against a repository's ratcheting baseline.

Rules (see HoneyDrunk.Standards/docs/CONVENTIONS.md, "File size and folder layout"):
- An owned C# file above warnLines warns; above failLines it fails unless the baseline lists it.
- A baselined file may shrink but never grow, and the baseline only ever loses entries.
- A layer root takes no C# files of its own; code goes in a folder per system or area.
- A folder holding more than maxFilesPerFolder C# files is flagged (advisory) so each system gets a subfolder.
"""
import argparse
import json
import os
from pathlib import Path
import posixpath
import subprocess
import sys

SCHEMA_VERSION = 1
DEFAULTS = {'warnLines': 400, 'failLines': 800, 'maxFilesPerFolder': 12}
# Directory names that never hold owned source: build output, Unity caches, vendor and generated code.
EXCLUDED_DIRECTORIES = {
    '.git', '.vs', '.idea', '.standards', 'bin', 'obj', 'node_modules', 'Library', 'Temp',
    'Packages', 'Plugins', 'ThirdParty', 'Generated',
}
GENERATED_SUFFIXES = ('.g.cs', '.g.i.cs', '.designer.cs', '.generated.cs', '.AssemblyInfo.cs', '.AssemblyAttributes.cs')
GENERATED_MARKER = '<auto-generated'
UPDATE_HINT = 'run check_file_layout.py --update-baseline and commit the baseline'


class LayoutError(Exception):
    """The configuration or baseline cannot be read."""


def load_config(root, config_path):
    """Settings from the config at config_path (repository-relative POSIX path)."""
    try:
        text = (root / config_path).read_text(encoding='utf-8')
    except OSError as exc:
        raise LayoutError(f'cannot read config {config_path}: {exc}') from exc
    return parse_config(text, config_path, config_path)


def parse_config(text, config_path, origin):
    try:
        config = json.loads(text)
    except ValueError as exc:
        raise LayoutError(f'{origin}: invalid JSON: {exc}') from exc
    if not isinstance(config, dict) or config.get('schemaVersion') != SCHEMA_VERSION:
        raise LayoutError(f'{origin}: schemaVersion must be {SCHEMA_VERSION}')
    sources = config.get('sources')
    if not sources or not all(isinstance(s, str) for s in sources):
        raise LayoutError(f'{origin}: sources must list the owned source directories')
    settings = {**DEFAULTS, **{k: config[k] for k in DEFAULTS if k in config}}
    if not 0 < settings['warnLines'] < settings['failLines']:
        raise LayoutError(f'{origin}: warnLines must be positive and below failLines')
    settings['sources'] = [_normal(s) for s in sources]
    settings['layerRoots'] = [_normal(s) for s in config.get('layerRoots', [])]
    settings['excludeDirectories'] = EXCLUDED_DIRECTORIES | set(config.get('excludeDirectories', []))
    default_baseline = posixpath.join(posixpath.dirname(config_path), 'file-layout-baseline.json')
    settings['baseline'] = _normal(config.get('baseline', default_baseline))
    return settings


def _normal(path):
    return posixpath.normpath(path.replace(chr(92), '/'))


def _relative(root, path):
    return path.resolve().relative_to(root.resolve()).as_posix()


def is_generated(path, text):
    name = path.name.lower()
    if any(name.endswith(suffix.lower()) for suffix in GENERATED_SUFFIXES):
        return True
    head = '\n'.join(text.splitlines()[:10])
    return GENERATED_MARKER in head


def owned_files(root, settings):
    """Map each owned C# file (repository-relative POSIX path) to its line count."""
    files = {}
    excluded = settings['excludeDirectories']
    for source in settings['sources']:
        start = root / source
        if not start.is_dir():
            raise LayoutError(f'source directory {source} does not exist')
        for directory, subdirectories, names in os.walk(start):
            subdirectories[:] = sorted(d for d in subdirectories if d not in excluded)
            for name in sorted(names):
                if not name.endswith('.cs'):
                    continue
                path = Path(directory) / name
                text = path.read_text(encoding='utf-8-sig', errors='replace')
                if not is_generated(path, text):
                    files[_relative(root, path)] = len(text.splitlines())
    return files


def read_baseline(text, origin):
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise LayoutError(f'{origin}: invalid JSON: {exc}') from exc
    if data.get('schemaVersion') != SCHEMA_VERSION:
        raise LayoutError(f'{origin}: schemaVersion must be {SCHEMA_VERSION}')
    oversized = data.get('oversizedFiles', {})
    roots = data.get('layerRootFiles', [])
    if not all(isinstance(v, int) and v > 0 for v in oversized.values()) or not isinstance(roots, list):
        raise LayoutError(f'{origin}: oversizedFiles maps paths to line counts; layerRootFiles lists paths')
    return {'oversizedFiles': dict(oversized), 'layerRootFiles': list(roots)}


def _git_show(root, ref, path):
    result = subprocess.run(['git', 'show', f'{ref}:{path}'], cwd=root, capture_output=True, text=True, encoding='utf-8', check=False)
    return result.stdout if result.returncode == 0 else None


def base_state(root, ref, config_path):
    """(settings, baseline) as committed at ref, found through the config committed there.

    None only on first adoption, when ref has no layout config. A config moved since ref is followed
    to its old path; a config deleted since ref, or one whose baseline is missing, fails closed, so
    moving either file cannot skip the comparison.
    """
    exists = subprocess.run(['git', 'rev-parse', '--verify', '--quiet', f'{ref}^{{commit}}'], cwd=root, capture_output=True, check=False)
    if exists.returncode != 0:
        raise LayoutError(f'base ref {ref} is not available; fetch it before comparing')
    config_path = renamed_paths(root, ref).get(config_path, config_path)
    config_text = _git_show(root, ref, config_path)
    if config_text is None:
        for deleted in _deleted_paths(root, ref):
            if deleted.endswith('.json') and _is_layout_config(_git_show(root, ref, deleted)):
                raise LayoutError(f'{ref} has a layout config at {deleted} that this change removes; keep its path or move it with git mv')
        return None
    settings = parse_config(config_text, config_path, f'{ref}:{config_path}')
    text = _git_show(root, ref, settings['baseline'])
    if text is None:
        raise LayoutError(f'{ref} has the layout config but not its baseline {settings["baseline"]}')
    return settings, read_baseline(text, f'{ref}:{settings["baseline"]}')


def weakened(settings, base):
    """How the config loosens the rules compared with the base config; loosening is an owner decision."""
    changes = [f'{key} raised from {base[key]} to {settings[key]}' for key in DEFAULTS if settings[key] > base[key]]
    changes += [f'source {s} removed' for s in base['sources'] if s not in settings['sources']]
    changes += [f'layer root {s} removed' for s in base['layerRoots'] if s not in settings['layerRoots']]
    changes += [f'directory {d} excluded' for d in sorted(settings['excludeDirectories'] - base['excludeDirectories'])]
    return changes


def renamed_paths(root, ref):
    """Map each file git sees as renamed since ref to its old path, so a moved baselined file keeps its entry."""
    result = subprocess.run(
        ['git', '-c', 'core.quotePath=false', 'diff', '--find-renames', '--name-status', '--diff-filter=R', ref, 'HEAD'],
        cwd=root, capture_output=True, text=True, encoding='utf-8', check=False,
    )
    if result.returncode != 0:
        raise LayoutError(f'cannot diff against {ref}: {result.stderr.strip()}')
    renames = {}
    for line in result.stdout.splitlines():
        parts = line.split('	')
        if len(parts) == 3:
            renames[parts[2]] = parts[1]
    return renames


def _deleted_paths(root, ref):
    result = subprocess.run(['git', '-c', 'core.quotePath=false', 'diff', '--find-renames', '--name-only', '--diff-filter=D', ref, 'HEAD'],
                            cwd=root, capture_output=True, text=True, encoding='utf-8', check=False)
    if result.returncode != 0:
        raise LayoutError(f'cannot diff against {ref}: {result.stderr.strip()}')
    return result.stdout.splitlines()


def _is_layout_config(text):
    try:
        data = json.loads(text or '')
    except ValueError:
        return False
    return isinstance(data, dict) and data.get('schemaVersion') == SCHEMA_VERSION and 'sources' in data


def root_files(files, settings):
    roots = set(settings['layerRoots'])
    return sorted(path for path in files if path.rpartition('/')[0] in roots)


def check(root, settings, baseline, base=None, renames=None):
    """Return (errors, warnings) as lists of (path, message).

    base is (settings, baseline) at the base ref; renames maps a moved file's new path to its old one.
    """
    errors, warnings = [], []
    files = owned_files(root, settings)
    warn, fail = settings['warnLines'], settings['failLines']
    oversized = baseline['oversizedFiles']
    for path, lines in sorted(files.items()):
        recorded = oversized.get(path)
        if recorded is not None:
            if lines > recorded:
                errors.append((path, f'{lines} lines, baselined at {recorded}: a baselined file may shrink but never grow. '
                                     'Put the new code in a new file in its system\'s folder.'))
            elif lines < recorded:
                errors.append((path, f'shrank from {recorded} to {lines} lines; lock the smaller size: {UPDATE_HINT}'))
        elif lines > fail:
            errors.append((path, f'{lines} lines is over the {fail}-line limit. Split it by system into its own folder.'))
        elif lines > warn:
            warnings.append((path, f'{lines} lines is over the {warn}-line guideline. Put new code in a new file rather than growing this one.'))
    for path in sorted(set(oversized) - set(files)):
        errors.append((path, f'baselined but no longer an owned file; {UPDATE_HINT}'))
    for path, recorded in sorted(oversized.items()):
        if path in files and files[path] <= fail and files[path] == recorded:
            errors.append((path, f'baselined at {recorded} lines, within the {fail}-line limit; {UPDATE_HINT}'))

    allowed_roots = set(baseline['layerRootFiles'])
    present_roots = root_files(files, settings)
    for path in present_roots:
        if path not in allowed_roots:
            errors.append((path, 'a layer root takes no new C# files. Put it in the folder for its system or area.'))
    for path in sorted(allowed_roots - set(present_roots)):
        errors.append((path, f'baselined layer-root file is gone; {UPDATE_HINT}'))

    counts = {}
    for path in files:
        folder = path.rpartition('/')[0]
        counts[folder] = counts.get(folder, 0) + 1
    for folder, count in sorted(counts.items()):
        if count > settings['maxFilesPerFolder']:
            warnings.append((folder, f'{count} C# files in one folder (guideline {settings["maxFilesPerFolder"]}). '
                                     'Give each system its own subfolder; put new files for a system there, not here.'))

    if base is not None:
        base_settings, base_baseline = base
        for change in weakened(settings, base_settings):
            errors.append((settings.get('config', ''), f'{change} compared with the base; the layout rules only ever tighten'))
        for path, lines in sorted(oversized.items()):
            before = base_baseline['oversizedFiles'].get(path)
            if before is None and renames and path in renames:
                before = base_baseline['oversizedFiles'].get(renames[path])
            if before is None:
                errors.append((path, 'added to the baseline; the baseline only ever loses entries. Split the file instead.'))
            elif lines > before:
                errors.append((path, f'baseline raised from {before} to {lines}; the baseline only ever loses entries or lowers counts'))
        for path in sorted(allowed_roots - set(base_baseline['layerRootFiles'])):
            errors.append((path, 'added to the layer-root baseline; the baseline only ever loses entries'))
    return errors, warnings


def updated_baseline(root, settings, baseline):
    """Lower counts and drop entries; never add or raise one."""
    files = owned_files(root, settings)
    oversized = {
        path: min(recorded, files[path])
        for path, recorded in sorted(baseline['oversizedFiles'].items())
        if path in files and files[path] > settings['failLines']
    }
    present = set(root_files(files, settings))
    roots = sorted(path for path in baseline['layerRootFiles'] if path in present)
    return {'schemaVersion': SCHEMA_VERSION, 'oversizedFiles': oversized, 'layerRootFiles': roots}


def initial_baseline(root, settings):
    files = owned_files(root, settings)
    oversized = {path: lines for path, lines in sorted(files.items()) if lines > settings['failLines']}
    return {'schemaVersion': SCHEMA_VERSION, 'oversizedFiles': oversized, 'layerRootFiles': root_files(files, settings)}


def write_json(path, data):
    temporary = path.with_name(path.name + '.tmp')
    temporary.write_text(json.dumps(data, indent=2) + '\n', encoding='utf-8')
    temporary.replace(path)


def report(kind, path, message):
    if os.environ.get('GITHUB_ACTIONS') == 'true':
        print(f'::{kind} file={path}::{message}')
    else:
        print(f'{kind}: {path}: {message}')


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--root', type=Path, default=Path.cwd(), help='repository root (default: current directory)')
    parser.add_argument('--config', type=Path, required=True, help='layout config JSON, relative to the root')
    parser.add_argument('--base-ref', help='git ref whose committed baseline this one may only shrink from (for example HEAD^1 on a pull request merge commit)')
    action = parser.add_mutually_exclusive_group()
    action.add_argument('--update-baseline', action='store_true', help='lower counts and remove entries that no longer apply; never adds one')
    action.add_argument('--init-baseline', action='store_true', help='create the first baseline; refused when one exists')
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        config_path = _relative(root, root / args.config)
        settings = load_config(root, config_path)
        settings['config'] = config_path
        baseline_path = root / settings['baseline']
        if args.init_baseline:
            if baseline_path.exists():
                parser.error(f'{settings["baseline"]} exists; a baseline is created once and then only shrinks')
            write_json(baseline_path, initial_baseline(root, settings))
            print(f'Wrote {settings["baseline"]}')
            return 0
        if not baseline_path.exists():
            raise LayoutError(f'baseline {settings["baseline"]} is missing; create it once with --init-baseline')
        baseline = read_baseline(baseline_path.read_text(encoding='utf-8'), settings['baseline'])
        if args.update_baseline:
            write_json(baseline_path, updated_baseline(root, settings, baseline))
            print(f'Updated {settings["baseline"]}')
            return 0
        base = base_state(root, args.base_ref, config_path) if args.base_ref else None
        renames = renamed_paths(root, args.base_ref) if base is not None else None
        errors, warnings = check(root, settings, baseline, base, renames)
    except (LayoutError, OSError) as exc:
        print(f'File layout check failed: {exc}', file=sys.stderr)
        return 2
    for path, message in warnings:
        report('warning', path, message)
    for path, message in errors:
        report('error', path, message)
    print(f'File layout: {len(errors)} error(s), {len(warnings)} advisory warning(s)')
    return 1 if errors else 0


if __name__ == '__main__':
    raise SystemExit(main())
