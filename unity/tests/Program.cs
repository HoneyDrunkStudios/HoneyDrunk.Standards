async Task Check(string name, string assembly, string path, string source, params string[] expected)
{
    var tree = CSharpSyntaxTree.ParseText(source, new CSharpParseOptions(LanguageVersion.CSharp9), path);
    var compilation = CSharpCompilation.Create(assembly, new[] { tree }, references,
        new CSharpCompilationOptions(OutputKind.DynamicallyLinkedLibrary, specificDiagnosticOptions: rules.SpecificDiagnosticOptions));
    var compilerErrors = compilation.GetDiagnostics().Where(d => d.Severity == DiagnosticSeverity.Error).ToArray();
    if (compilerErrors.Length != 0) throw new Exception(name + ": " + string.Join("; ", compilerErrors.Select(d => d.ToString())));
    var diagnostics = await compilation.WithAnalyzers(analyzers).GetAnalyzerDiagnosticsAsync();
    var failures = diagnostics.Where(d => d.Id == "AD0001" || d.Severity == DiagnosticSeverity.Error || d.Id == "HD0051" || rules.SpecificDiagnosticOptions.ContainsKey(d.Id)).ToArray();
    if (!failures.Select(d => d.Id).Order().SequenceEqual(expected.Order()))
        throw new Exception(name + ": expected " + string.Join(",", expected) + "; got " + string.Join("; ", diagnostics));
    if (failures.Any(d => d.Severity != DiagnosticSeverity.Error)) throw new Exception(name + ": rule is not an error");
    tests++;
}

